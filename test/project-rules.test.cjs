const assert = require("node:assert/strict");
const { execFileSync } = require("node:child_process");
const fs = require("node:fs/promises");
const { dirname, join } = require("node:path");
const { test } = require("node:test");
const { classify } = require("../dist/core/classify");
const {
  cleanupExclusion, clearProjectRuleCache, discoverProjectCandidates, freshProjectLabel, gitIgnoreEvidence,
  recheckProjectCandidate,
} = require("../dist/core/project-rules");

async function fixture(t) {
  const root = await fs.mkdtemp(join(__dirname, ".shulker-rules-"));
  const previous = process.env.SHULKER_CONFIG;
  const config = join(root, ".shulker.json");
  process.env.SHULKER_CONFIG = config;
  await fs.writeFile(config, "{}");
  clearProjectRuleCache();
  t.after(async () => {
    if (previous === undefined) delete process.env.SHULKER_CONFIG;
    else process.env.SHULKER_CONFIG = previous;
    clearProjectRuleCache();
    await fs.rm(root, { recursive: true, force: true });
  });
  return {
    root,
    config,
    async file(relative, content = "fixture data") {
      const path = join(root, relative);
      await fs.mkdir(dirname(path), { recursive: true });
      await fs.writeFile(path, content);
      return path;
    },
  };
}

test("project markers and fingerprints distinguish artifacts from same-name user folders", async (t) => {
  const { root, file } = await fixture(t);
  const cases = [
    ["plain/node_modules/source.js", "plain/node_modules", "yours"],
    ["photos/target/portraits.txt", "photos/target", "yours"],
    ["rust/target/notes.txt", "rust/target", "yours"],
    ["rust-real/target/debug/build.txt", "rust-real/target", "junk"],
    ["nested/app/node_modules/library/index.js", "nested/app/node_modules", "junk"],
    ["nested/python/environment-local/pyvenv.cfg", "nested/python/environment-local", "unused"],
    ["nested/python/venv/notes.txt", "nested/python/venv", "yours"],
    ["flutter/windows/flutter/ephemeral/cache.bin", "flutter/windows/flutter/ephemeral", "junk"],
  ];
  for (const [relative] of cases) await file(relative);
  await file("rust/Cargo.toml");
  await file("rust/target/CACHEDIR.TAG/notes.txt");
  await file("rust-real/Cargo.toml");
  await file("rust-real/target/.rustc_info.json");
  await file("nested/app/package.json", "{}");
  await file("flutter/pubspec.yaml");

  for (const [, relative, verdict] of cases) {
    const path = join(root, relative);
    assert.equal(classify({ path, dir: true, size: 1 }, "documents", { at: 0, kind: "changed" }).verdict, verdict, relative);
  }
  const staleCandidate = { path: join(root, "rust-real/target"), dir: true, size: 1 };
  await fs.rm(join(staleCandidate.path, ".rustc_info.json"));
  assert.equal(freshProjectLabel(staleCandidate), null);

  const result = await discoverProjectCandidates([root, join(root, "nested")]);
  assert.equal(result.truncated, false);
  assert.deepEqual(result.candidates.map(({ path }) => path).sort(), [
    join(root, "flutter/windows/flutter/ephemeral"),
    join(root, "nested/app/node_modules"),
    join(root, "nested/python/environment-local"),
  ].sort());
  const environment = result.candidates.find(({ path }) => path.endsWith("environment-local"));
  const marker = await fs.stat(join(environment.path, "pyvenv.cfg"));
  assert.equal(environment.size, process.platform === "win32" ? marker.size : marker.blocks * 512);
});

test("exclusions protect the containing folder and custom paths stay review-only", async (t) => {
  const { root, config, file } = await fixture(t);
  const hidden = await file("node/node_modules/local/settings.json");
  const path = await file("other/generated.bin");
  await file("node/package.json");
  await fs.writeFile(config, JSON.stringify({
    exclude: [hidden],
    rules: [{ path, reason: "generated by my processing job" }],
  }));
  assert(cleanupExclusion(join(root, "node", "node_modules")));
  assert(cleanupExclusion(hidden));
  assert(!cleanupExclusion(hidden + ".bak"));
  const result = await discoverProjectCandidates([root]);
  assert.deepEqual(result.candidates.map((entry) => entry.path), [path]);
  assert.equal(result.candidates[0].label.cleanup, "review");

  await fs.writeFile(config, "{malformed");
  clearProjectRuleCache();
  assert.match(cleanupExclusion(path), /Cannot read cleanup configuration/);
  assert.deepEqual((await discoverProjectCandidates([root])).candidates, []);
});

test("discovery bounds its work and never offers a directory containing a protected disk", async (t) => {
  const { root, file } = await fixture(t);
  await file("node/package.json");
  await file("node/node_modules/dependency/data.bin");
  const item = { path: join(root, "node", "node_modules"), dir: true, size: 1 };
  assert.equal((await recheckProjectCandidate(item)).cleanup, "rebuildable");
  await file("node/node_modules/dependency/docker-data.vhdx");
  assert.equal(await recheckProjectCandidate(item), null);
  assert.deepEqual((await discoverProjectCandidates([root])).candidates, []);
  assert.equal((await discoverProjectCandidates([root], { maxDirectories: 1 })).truncated, true);
});

test("Git ignores are review evidence and cannot authorize deletion", async (t) => {
  const { root, file } = await fixture(t);
  try {
    execFileSync("git", ["--version"], { stdio: "ignore" });
  } catch {
    t.skip("Git is unavailable");
    return;
  }
  execFileSync("git", ["-C", root, "init", "-q"], { stdio: "ignore" });
  await file(".gitignore", "out/*\n!out/keep.txt\n");
  const ignored = await file("out/data.bin");
  const retained = await file("out/keep.txt");
  assert.deepEqual(await gitIgnoreEvidence(ignored), {
    verdict: "unused", cleanup: "blocked", reason: "ignored by Git · inspect in your project before removing",
  });
  assert.equal(await gitIgnoreEvidence(retained), null);
});
